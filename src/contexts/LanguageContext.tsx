export const languageNames: Record<Language, string> = {
  'en-US': 'English (US)',
  'en-UK': 'English (UK)',
  'zh-CN': '简体中文',
  'zh-TW': '繁體中文',
  'es': 'Español',
  'ja': '日本語',
  'ko': '한국어',
  'de': 'Deutsch',
  'fr': 'Français',
};

const allLanguages: Language[] = ['en-US', 'en-UK', 'zh-CN', 'zh-TW', 'es', 'ja', 'ko', 'de', 'fr'];

function detectBrowserLanguage(): Language {
  const browserLang = navigator.language || (navigator as any).userLanguage || 'en';
  const lower = browserLang.toLowerCase();

  if (lower.startsWith('zh-tw') || lower.startsWith('zh-hant')) return 'zh-TW';
  if (lower.startsWith('zh')) return 'zh-CN';
  if (lower.startsWith('ja')) return 'ja';
  if (lower.startsWith('ko')) return 'ko';
  if (lower.startsWith('de')) return 'de';
  if (lower.startsWith('fr')) return 'fr';
  if (lower.startsWith('es')) return 'es';
  if (lower === 'en-gb' || lower === 'en-uk') return 'en-UK';
  return 'en-US';
}

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  languageNames: Record<Language, string>;
  availableLanguages: Language[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('lumiere-language');
    if (saved && allLanguages.includes(saved as Language)) return saved as Language;
    return detectBrowserLanguage();
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('lumiere-language', lang);
  };

  const t = (key: string): string => {
    return translations[language]?.[key] ?? translations['en-US']?.[key] ?? key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, languageNames, availableLanguages: allLanguages }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
};
